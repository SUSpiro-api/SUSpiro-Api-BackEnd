-- Guias médicas. Toda guia referencia um paciente cadastrado (fk_guias_paciente);
-- nome e CPF ficam registrados como estavam no cadastro no momento da emissão.
CREATE TABLE guias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id UUID NOT NULL,
    paciente_nome VARCHAR(150) NOT NULL,
    paciente_cpf VARCHAR(11) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    especialidade VARCHAR(120),
    detalhe VARCHAR(255),
    data_solicitada DATE NOT NULL,
    observacao VARCHAR(1000),
    prioridade VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL,
    solicitante_id BIGINT NOT NULL REFERENCES usuarios (id),
    solicitante_nome VARCHAR(150) NOT NULL,
    data_agendamento DATE,
    hora_agendamento TIME,
    agendado_por_id BIGINT REFERENCES usuarios (id),
    agendado_por_nome VARCHAR(150),
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_guias_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
    CONSTRAINT chk_guias_tipo CHECK (tipo IN ('CONSULTA', 'RETORNO', 'EXAME', 'ENCAMINHAMENTO')),
    CONSTRAINT chk_guias_prioridade CHECK (prioridade IN ('NORMAL', 'URGENTE')),
    CONSTRAINT chk_guias_status CHECK (status IN ('AGUARDANDO_AGENDAMENTO', 'AGENDADO', 'CANCELADO'))
);

CREATE INDEX idx_guias_paciente ON guias (paciente_id, criado_em DESC, id DESC);
CREATE INDEX idx_guias_solicitante ON guias (solicitante_id, criado_em DESC);
CREATE INDEX idx_guias_fila ON guias (status, prioridade DESC, criado_em ASC);
