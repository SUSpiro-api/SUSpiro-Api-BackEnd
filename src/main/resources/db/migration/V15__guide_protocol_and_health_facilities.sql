CREATE TABLE estabelecimentos_saude (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(180) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    logradouro VARCHAR(180) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    complemento VARCHAR(120),
    bairro VARCHAR(120) NOT NULL,
    cidade VARCHAR(120) NOT NULL,
    estado VARCHAR(2) NOT NULL,
    cep VARCHAR(8) NOT NULL,
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_estabelecimentos_tipo CHECK (tipo IN ('HOSPITAL','CLINICA','UBS','LABORATORIO','CENTRO_MEDICO')),
    CONSTRAINT chk_estabelecimentos_estado CHECK (estado ~ '^[A-Z]{2}$'),
    CONSTRAINT chk_estabelecimentos_cep CHECK (cep ~ '^[0-9]{8}$')
);
CREATE INDEX idx_estabelecimentos_cidade_estado_ativo
    ON estabelecimentos_saude (ativo, UPPER(cidade), UPPER(estado), nome);
CREATE INDEX idx_estabelecimentos_estado_cidade_ativo
    ON estabelecimentos_saude (ativo, UPPER(estado), cidade, nome);

