CREATE TABLE requisicoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(10) NOT NULL UNIQUE,
    paciente_id UUID NOT NULL REFERENCES pacientes (id),
    solicitante_id BIGINT NOT NULL REFERENCES usuarios (id),
    descricao VARCHAR(255) NOT NULL,
    observacao VARCHAR(500),
    data_vencimento DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_requisicoes_status
        CHECK (status IN ('PENDENTE', 'AGENDADA', 'CONCLUIDA', 'VENCIDA'))
);

CREATE INDEX idx_requisicoes_paciente ON requisicoes (paciente_id);

CREATE INDEX idx_requisicoes_status_vencimento
    ON requisicoes (status, data_vencimento);

COMMENT ON COLUMN requisicoes.protocolo IS
    'Numero aleatorio gerado no cadastro para o paciente acompanhar a requisicao.';
